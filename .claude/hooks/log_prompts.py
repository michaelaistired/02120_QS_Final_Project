"""Write every prompt the student typed into journal/prompts.md (readable build journal).

Runs as a Claude Code UserPromptSubmit hook (and can be run by hand: python log_prompts.py).
It rebuilds prompts.md from all session logs every time, so it never duplicates entries and
also picks up prompts from sessions before this hook existed. The course's save_journal.py
still copies the full session logs; this file is only a readable index of the prompts.
"""

import json
import os
import re
import sys
from pathlib import Path


def project_dir() -> Path:
    env_dir = os.environ.get("CLAUDE_PROJECT_DIR")
    return Path(env_dir) if env_dir else Path(__file__).resolve().parent.parent.parent


def read_hook_input() -> dict:
    if sys.stdin is None or sys.stdin.isatty():
        return {}
    try:
        return json.loads(sys.stdin.read() or "{}")
    except json.JSONDecodeError:
        return {}


def log_files(hook_input: dict, project: Path) -> list:
    """Session logs to scan: Claude Code's own log folder plus the journal copies."""
    transcript = hook_input.get("transcript_path")
    if transcript:
        source = Path(transcript).expanduser().parent
    else:
        slug = re.sub(r"[^A-Za-z0-9]", "-", str(project.resolve()))
        source = Path.home() / ".claude" / "projects" / slug
    files = {}
    for folder in (project / "journal", source):
        if folder.is_dir():
            for f in folder.glob("*.jsonl"):
                files[f.name] = f  # Claude's live log (scanned last) wins over the copy
    return list(files.values())


def typed_prompts(path: Path) -> list:
    """(timestamp, session, text) for each prompt the student typed in one session log."""
    out = []
    for line in path.open(encoding="utf-8", errors="replace"):
        try:
            entry = json.loads(line)
        except json.JSONDecodeError:
            continue
        if entry.get("type") != "user" or entry.get("isMeta"):
            continue
        content = entry.get("message", {}).get("content")
        if isinstance(content, list):  # tool results are lists; typed text may be too
            content = "\n".join(c.get("text", "") for c in content
                                if isinstance(c, dict) and c.get("type") == "text")
        if not isinstance(content, str) or not content.strip():
            continue
        if content.lstrip().startswith("<"):  # slash-command echoes, caveats, notifications
            continue
        out.append((entry.get("timestamp", ""), path.stem, content.strip()))
    return out


def main() -> None:
    project = project_dir()
    hook_input = read_hook_input()
    prompts = []
    for f in log_files(hook_input, project):
        prompts += typed_prompts(f)
    current = (hook_input.get("prompt") or "").strip()
    if current and current not in {p[2] for p in prompts}:  # not written to the log yet
        prompts.append(("9999 (just submitted)", hook_input.get("session_id", "current"), current))
    prompts.sort()

    lines = ["# Prompts typed into Claude Code", "",
             "Auto-generated by `.claude/hooks/log_prompts.py` on every prompt. "
             "Full sessions (including Claude's replies) are in the `.jsonl` files here.", ""]
    for i, (ts, session, text) in enumerate(prompts, 1):
        lines += [f"## {i}. {ts}  (session {session[:8]})", "", text, ""]
    journal = project / "journal"
    journal.mkdir(exist_ok=True)
    (journal / "prompts.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    try:
        main()
    except Exception as error:  # a journal problem must never block a prompt
        print(f"log_prompts: {error}", file=sys.stderr)
